import * as Location from 'expo-location';
import { ordersApi } from '../../../api/orders.api';
import { createProductionArrivalProofController, createProductionOrderLocationTracker, captureFreshOrderPosition } from './arrival-proof-production';
import type { ArrivalProofDependencies } from './arrival-proof-controller';
import type { createOrderLocationTracker } from './order-location-tracker';
type OrderLocationTrackerDependencies = Parameters<typeof createOrderLocationTracker>[0];
const mockKey = { userId: 'tech', role: 'technician' as const, sessionGeneration: 1, serviceOrderId: 'order' };
let mockAuth = { isAuthenticated: true, user: { id: 'tech', role: 'technician' }, sessionGeneration: 1 };
let mockCommand!: ArrivalProofDependencies;
let mockLocation!: OrderLocationTrackerDependencies;
jest.mock('./arrival-proof-controller', () => ({ createArrivalProofController: (deps: ArrivalProofDependencies) => { mockCommand = deps; return {}; } }));
jest.mock('./order-location-tracker', () => ({ createOrderLocationTracker: (deps: OrderLocationTrackerDependencies) => { mockLocation = deps; return {}; } }));
jest.mock('../runtime/entry-attempt-production', () => ({ newEntryIntentId: () => 'intent' }));
jest.mock('../../../store/auth.store', () => ({ useAuthStore: { getState: () => mockAuth } }));
jest.mock('../../../api/orders.api', () => ({ ordersApi: { enRoute: jest.fn(), checkIn: jest.fn(), uploadCheckInFace: jest.fn(), uploadEvidenceBefore: jest.fn(), startRepair: jest.fn(), deleteEvidence: jest.fn(), updateOrderLocation: jest.fn() } }));
jest.mock('expo-location', () => ({ Accuracy: { High: 4 }, requestForegroundPermissionsAsync: jest.fn(), getForegroundPermissionsAsync: jest.fn(), getCurrentPositionAsync: jest.fn(), watchPositionAsync: jest.fn() }));
const runtime = { coordinator: {} as ArrivalProofDependencies['coordinator'], journal: {} as ArrivalProofDependencies['journal'], getKey: () => mockKey, isActive: () => true };
beforeEach(() => { jest.clearAllMocks(); mockAuth = { isAuthenticated: true, user: { id: 'tech', role: 'technician' }, sessionGeneration: 1 }; });
it('production command uses exact private order APIs and synchronously fences renewed or wrong role auth', () => {
  createProductionArrivalProofController(runtime);
  expect(mockCommand.getKey()).toEqual(mockKey);
  expect(mockCommand.transport).toEqual({ depart: ordersApi.enRoute, checkIn: ordersApi.checkIn, uploadFace: ordersApi.uploadCheckInFace, uploadBefore: ordersApi.uploadEvidenceBefore, recoverRepair: ordersApi.startRepair, deleteEvidence: ordersApi.deleteEvidence });
  mockAuth.sessionGeneration = 2; expect(mockCommand.getKey()).toBeNull();
  mockAuth.sessionGeneration = 1; mockAuth.user.role = 'customer'; expect(mockCommand.getKey()).toBeNull();
  mockAuth.user.role = 'technician'; mockAuth.isAuthenticated = false; expect(mockCommand.getKey()).toBeNull();
});
it('point of use permission denial never reads GPS; granted uses fresh current OS sample with unknown accuracy rejected later', async () => {
  (Location.requestForegroundPermissionsAsync as jest.Mock).mockResolvedValueOnce({ granted: false });
  expect((await captureFreshOrderPosition()).permission).toBe('denied'); expect(Location.getCurrentPositionAsync).not.toHaveBeenCalled();
  (Location.requestForegroundPermissionsAsync as jest.Mock).mockResolvedValueOnce({ granted: true });
  (Location.getCurrentPositionAsync as jest.Mock).mockResolvedValueOnce({ timestamp: 123, coords: { latitude: 10, longitude: 106, accuracy: null } });
  const sample = await captureFreshOrderPosition();
  expect(Location.getCurrentPositionAsync).toHaveBeenCalledWith({ accuracy: Location.Accuracy.High });
  expect(sample).toMatchObject({ source: 'os', permission: 'granted', lat: 10, lng: 106, timestamp: 123 }); expect(sample.accuracyMeters).toBeNaN();
});
it('background tracker never prompts permissions and disposes exact native watcher', async () => {
  createProductionOrderLocationTracker(runtime);
  expect(mockLocation.patch).toBe(ordersApi.updateOrderLocation);
  (Location.getForegroundPermissionsAsync as jest.Mock).mockResolvedValueOnce({ granted: false });
  await expect(mockLocation.watch(jest.fn())).rejects.toThrow('Location permission required');
  expect(Location.requestForegroundPermissionsAsync).not.toHaveBeenCalled(); expect(Location.watchPositionAsync).not.toHaveBeenCalled();
  (Location.getForegroundPermissionsAsync as jest.Mock).mockResolvedValueOnce({ granted: true });
  const remove = jest.fn(), onPosition = jest.fn();
  (Location.watchPositionAsync as jest.Mock).mockResolvedValueOnce({ remove });
  const stop = await mockLocation.watch(onPosition);
  const [options, receive] = (Location.watchPositionAsync as jest.Mock).mock.calls[0];
  expect(options).toEqual({ accuracy: Location.Accuracy.High, timeInterval: 15000, distanceInterval: 20 });
  receive({ timestamp: 123, coords: { latitude: 10, longitude: 106, accuracy: 9 } });
  expect(onPosition).toHaveBeenCalledWith({ source: 'os', permission: 'granted', lat: 10, lng: 106, accuracyMeters: 9, timestamp: 123 });
  stop(); expect(remove).toHaveBeenCalledTimes(1);
});
